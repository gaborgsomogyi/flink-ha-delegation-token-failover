package com.example.failover.driver.setup;

import com.example.failover.driver.config.RunConfig;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/** The processes of a run and the generated Flink configuration. */
public final class Topology {

    private Topology() {}

    public static ProcessSpec zookeeper() {
        return new ProcessSpec("zookeeper", ProcessSpec.Role.ZOOKEEPER, 0);
    }

    public static List<ProcessSpec> jobManagers(RunConfig config) {
        final List<ProcessSpec> result = new ArrayList<>();
        for (int i = 1; i <= config.jobManagers(); i++) {
            result.add(
                    new ProcessSpec(
                            "jm" + i, ProcessSpec.Role.JOB_MANAGER, config.restPortBase() + i - 1));
        }
        return result;
    }

    public static List<ProcessSpec> taskManagers(RunConfig config) {
        final List<ProcessSpec> result = new ArrayList<>();
        for (int i = 1; i <= config.taskManagers(); i++) {
            result.add(new ProcessSpec("tm" + i, ProcessSpec.Role.TASK_MANAGER, 0));
        }
        return result;
    }

    /**
     * The config.yaml of one Flink process. Everything not set here keeps its default, in
     * particular the heartbeat and the ZooKeeper retry settings. The env.* settings of the
     * distribution are repeated, because this file replaces the one of the distribution and the
     * JVMs fail without the --add-opens flags that it ships for Java 17.
     */
    static String flinkConfig(
            RunConfig config, ProcessSpec process, Map<String, String> distributionEnvOptions) {
        final StringBuilder yaml = new StringBuilder();
        yaml.append("# generated by the failover driver, do not edit\n");
        // The hostname of the container is its name, and the containers share a network.
        yaml.append("jobmanager.rpc.address: ").append(process.name()).append('\n');
        yaml.append("jobmanager.bind-host: 0.0.0.0\n");
        yaml.append("jobmanager.memory.process.size: ")
                .append(config.jobManagerMemory())
                .append('\n');
        yaml.append("rest.address: ").append(process.name()).append('\n');
        yaml.append("rest.bind-address: 0.0.0.0\n");
        yaml.append("rest.port: 8081\n");
        yaml.append("taskmanager.host: ").append(process.name()).append('\n');
        yaml.append("taskmanager.bind-host: 0.0.0.0\n");
        yaml.append("taskmanager.memory.process.size: ")
                .append(config.taskManagerMemory())
                .append('\n');
        yaml.append("taskmanager.numberOfTaskSlots: ")
                .append(RunConfig.SLOTS_PER_TASK_MANAGER)
                .append('\n');
        yaml.append("parallelism.default: 1\n");

        yaml.append("high-availability.type: zookeeper\n");
        yaml.append("high-availability.zookeeper.quorum: zookeeper:2181\n");
        yaml.append("high-availability.zookeeper.path.root: /flink\n");
        yaml.append("high-availability.cluster-id: /failover\n");
        yaml.append("high-availability.storageDir: tokenfs:///data/ha\n");
        // A killed leader holds its ZooKeeper node until the session times out.
        yaml.append("high-availability.zookeeper.client.session-timeout: 5 s\n");
        yaml.append("high-availability.zookeeper.client.connection-timeout: 5 s\n");

        yaml.append("state.checkpoints.dir: tokenfs:///data/checkpoints\n");
        yaml.append("execution.checkpointing.interval: 10 s\n");
        // Small state would be inlined into the metadata file of the JobManager, so that the
        // TaskManagers would not touch the file system at all.
        yaml.append("execution.checkpointing.data-inline-threshold: 0 b\n");

        yaml.append("security.delegation.tokens.enabled: true\n");
        yaml.append("security.delegation.tokens.renewal.time-ratio: ")
                .append(config.renewalRatio())
                .append('\n');
        yaml.append("security.delegation.token.provider.mock-expiring.lifetime: ")
                .append(config.tokenLifetime().toMillis())
                .append(" ms\n");

        for (Map.Entry<String, String> option : distributionEnvOptions.entrySet()) {
            yaml.append(option.getKey()).append(": ").append(option.getValue()).append('\n');
        }
        return yaml.toString();
    }

    /**
     * The log configuration of a Flink process: the default console pattern, additionally written
     * to a file which the driver reads (the leader is detected from it).
     */
    static String log4jConsoleProperties() {
        return String.join(
                        "\n",
                        "rootLogger.level = INFO",
                        "rootLogger.appenderRef.console.ref = ConsoleAppender",
                        "rootLogger.appenderRef.file.ref = FileAppender",
                        "",
                        "appender.console.name = ConsoleAppender",
                        "appender.console.type = CONSOLE",
                        "appender.console.layout.type = PatternLayout",
                        "appender.console.layout.pattern = %d{yyyy-MM-dd HH:mm:ss,SSS} %-5p %-60c %x - %m%n",
                        "",
                        "appender.file.name = FileAppender",
                        "appender.file.type = File",
                        "appender.file.fileName = /logs/${env:DTM_PROCESS_NAME}.log",
                        "appender.file.append = true",
                        "appender.file.layout.type = PatternLayout",
                        "appender.file.layout.pattern = %d{yyyy-MM-dd HH:mm:ss,SSS} %-5p %-60c %x - %m%n",
                        "",
                        "logger.pekko.name = org.apache.pekko",
                        "logger.pekko.level = INFO",
                        "logger.kafka.name = org.apache.kafka",
                        "logger.kafka.level = OFF",
                        "logger.hadoop.name = org.apache.hadoop",
                        "logger.hadoop.level = WARN",
                        "logger.zookeeper.name = org.apache.zookeeper",
                        "logger.zookeeper.level = INFO",
                        "logger.curator.name = org.apache.flink.shaded.curator5",
                        "logger.curator.level = INFO",
                        "")
                + "\n";
    }
}
