package com.example.failover.driver.setup;

import com.example.failover.driver.config.RunConfig;

import java.nio.file.Path;
import java.util.List;

/** Renders the docker compose file of a run. */
final class ComposeFile {

    private ComposeFile() {}

    static String render(
            RunConfig config,
            Path runDirectory,
            ProcessSpec zookeeper,
            List<ProcessSpec> jobManagers,
            List<ProcessSpec> taskManagers) {
        final StringBuilder yaml = new StringBuilder();
        yaml.append("# generated by the failover driver, do not edit\n");
        yaml.append("services:\n");

        yaml.append("  ").append(zookeeper.name()).append(":\n");
        yaml.append("    image: ").append(config.zookeeperImage()).append('\n');
        yaml.append("    container_name: ").append(zookeeper.container()).append('\n');
        yaml.append("    hostname: ").append(zookeeper.name()).append('\n');
        yaml.append("    restart: \"no\"\n");

        for (ProcessSpec jobManager : jobManagers) {
            flinkService(yaml, config, runDirectory, zookeeper, jobManager, "jobmanager.sh");
        }
        for (ProcessSpec taskManager : taskManagers) {
            flinkService(yaml, config, runDirectory, zookeeper, taskManager, "taskmanager.sh");
        }
        return yaml.toString();
    }

    private static void flinkService(
            StringBuilder yaml,
            RunConfig config,
            Path runDirectory,
            ProcessSpec zookeeper,
            ProcessSpec process,
            String script) {
        yaml.append("  ").append(process.name()).append(":\n");
        yaml.append("    image: ").append(config.runtimeImage()).append('\n');
        yaml.append("    container_name: ").append(process.container()).append('\n');
        yaml.append("    hostname: ").append(process.name()).append('\n');
        // The scripts end in "exec java", so the JVM is the main process of the container.
        yaml.append("    command: [\"/opt/flink/bin/")
                .append(script)
                .append("\", \"start-foreground\"]\n");
        yaml.append("    environment:\n");
        yaml.append("      FLINK_CONF_DIR: /conf\n");
        yaml.append("      FLINK_PLUGINS_DIR: /plugins\n");
        yaml.append("      FLINK_LOG_DIR: /tmp/flink-log\n");
        yaml.append("      FLINK_PID_DIR: /tmp\n");
        yaml.append("      DTM_PROCESS_NAME: ").append(process.name()).append('\n');
        yaml.append("      DTM_AUDIT_DIR: /audit\n");
        yaml.append("    volumes:\n");
        yaml.append("      - \"").append(config.flinkHome()).append(":/opt/flink:ro\"\n");
        yaml.append("      - \"")
                .append(runDirectory.resolve("conf").resolve(process.name()))
                .append(":/conf:ro\"\n");
        yaml.append("      - \"")
                .append(runDirectory.resolve("plugins"))
                .append(":/plugins:ro\"\n");
        yaml.append("      - \"").append(runDirectory.resolve("data")).append(":/data\"\n");
        yaml.append("      - \"").append(runDirectory.resolve("audit")).append(":/audit\"\n");
        yaml.append("      - \"").append(runDirectory.resolve("logs")).append(":/logs\"\n");
        if (process.isJobManager()) {
            yaml.append("    ports:\n");
            yaml.append("      - \"127.0.0.1:").append(process.restHostPort()).append(":8081\"\n");
        }
        yaml.append("    depends_on:\n");
        yaml.append("      - ").append(zookeeper.name()).append('\n');
        yaml.append("    restart: \"no\"\n");
    }
}
